"""Show the virtual obstacle cylinders inside FlightGear as tornadoes.

The controller's obstacles live only in Python (local east/north metres around
the first telemetry fix). This module places a tornado model at each one through
FlightGear's telnet property server (--telnet=5500), so what the fly is
avoiding is visible in the sim, not only in the matplotlib companion.

Each obstacle i gets /models/model[900+i] (loaded once per FlightGear session)
whose position, size and visibility follow /fruitfly/obstacles/obstacle[i]/...
Re-running the controller just rewrites those properties, so tornadoes move
instead of piling up. Models: flightgear/Aircraft/FlyCabin/Models/Obstacles/
(generated by flightgear/tools/make_obstacles.py); FlightGear must be started
with --fg-aircraft=<repo>/flightgear/Aircraft, as both launchers do.
"""
import math
import socket

EARTH_R = 6371000  # same sphere as flightgear.FlightGear.parse
MAX_OBSTACLES = 32  # models generated by make_obstacles.py
MODEL_BASE = 900    # /models/model[] index of obstacle 0; clear of scenery/AI models
MODEL_PATH = 'Aircraft/FlyCabin/Models/Obstacles/obstacle-{i}.xml'
ROOT = '/fruitfly/obstacles'


def to_latlon(origin, east, north):
    """Inverse of the local frame in FlightGear.parse (equirectangular at origin)."""
    lat0, lon0 = origin
    lat = lat0 + math.degrees(north / EARTH_R)
    lon = lon0 + math.degrees(east / (EARTH_R * math.cos(math.radians(lat0))))
    return lat, (lon + 180) % 360 - 180


def obstacle_props(i, obstacle, origin):
    lat, lon = to_latlon(origin, obstacle.east, obstacle.north)
    base = f'{ROOT}/obstacle[{i}]'
    return [(f'{base}/name', obstacle.name),
            (f'{base}/latitude-deg', f'{lat:.8f}'), (f'{base}/longitude-deg', f'{lon:.8f}'),
            (f'{base}/elevation-ft', f'{obstacle.bottom / 0.3048:.1f}'),
            (f'{base}/radius-m', f'{obstacle.radius:.1f}'),
            (f'{base}/height-m', f'{obstacle.top - obstacle.bottom:.1f}'),
            (f'{base}/threat', '0'), (f'{base}/visible', 'true')]


def model_props(i):
    """Properties that make FlightGear's model manager load tornado i.

    The model manager loads /models/model[n] when its 'load' child appears, so
    'load' must come last. The -prop entries make the model follow the
    /fruitfly/obstacles values every frame.
    """
    node, src = f'/models/model[{MODEL_BASE + i}]', f'{ROOT}/obstacle[{i}]'
    return [(f'{node}/path', MODEL_PATH.format(i=i)),
            (f'{node}/latitude-deg-prop', f'{src}/latitude-deg'),
            (f'{node}/longitude-deg-prop', f'{src}/longitude-deg'),
            (f'{node}/elevation-ft-prop', f'{src}/elevation-ft'),
            (f'{node}/heading-deg', '0'), (f'{node}/pitch-deg', '0'), (f'{node}/roll-deg', '0'),
            (f'{node}/load', 'true')]


class ObstacleScene:
    def __init__(self, port=5500, host='127.0.0.1', timeout=2.0):
        self.sock = socket.create_connection((host, port), timeout=timeout)
        self.sock.settimeout(timeout)
        self.names = []
        self.threats = {}
        self._send('data')  # no prompts or echoed values

    def _send(self, *lines):
        self.sock.sendall(''.join(line + '\r\n' for line in lines).encode('ascii'))

    def _set(self, pairs):
        for path, value in pairs:
            if any(c in str(value) for c in '\r\n'):
                raise ValueError(f'Bad property value for {path}')
        self._send(*(f'set {path} {value}' for path, value in pairs))

    def get(self, path):
        self._send(f'get {path}')
        data = b''
        while not data.endswith(b'\n'):
            chunk = self.sock.recv(4096)
            if not chunk:
                raise ConnectionError('FlightGear closed the telnet connection')
            data += chunk
        return data.decode('ascii', 'replace').strip()

    def publish(self, obstacles, origin):
        """Place one tornado per obstacle and hide unused ones. Returns the count shown."""
        shown = list(obstacles)[:MAX_OBSTACLES]
        self.names = [o.name for o in shown]
        self.threats = {}
        for i, obstacle in enumerate(shown):
            self._set(obstacle_props(i, obstacle, origin))
            # 'loaded' is our own marker so a second controller run in the same
            # FlightGear session reuses the model instead of loading another.
            if self.get(f'{ROOT}/obstacle[{i}]/loaded') not in ('true', '1'):
                self._set(model_props(i) + [(f'{ROOT}/obstacle[{i}]/loaded', 'true')])
        self._set([(f'{ROOT}/obstacle[{i}]/visible', 'false')
                   for i in range(len(shown), MAX_OBSTACLES)])
        self._set([(f'{ROOT}/count', str(len(shown)))])
        return len(shown)

    def threat(self, name, level=1.0):
        """Light up the obstacle the fly is reacting to (name '' clears all)."""
        level = max(0.0, min(1.0, level))
        changes = []
        for i, n in enumerate(self.names):
            want = round(level, 2) if n == name and name else 0.0
            if abs(self.threats.get(i, 0.0) - want) >= 0.05 or (want == 0) != (self.threats.get(i, 0.0) == 0):
                self.threats[i] = want
                changes.append((f'{ROOT}/obstacle[{i}]/threat', f'{want:.2f}'))
        if changes:
            self._set(changes)

    def close(self):
        try:
            self.threat('')
        except OSError:
            pass
        finally:
            self.sock.close()
