"""Generate the FlightGear models that show the virtual obstacle cylinders.

The obstacle-avoidance controller (flight_simulator/, scenarios/obstacles.json)
treats obstacles as vertical cylinders that exist only in Python. To see them
in the sim, flight_simulator/fg_scene.py loads one tower model per obstacle at
runtime over the telnet property server and drives it from properties:

    /fruitfly/obstacles/obstacle[i]/latitude-deg, longitude-deg   position
    /fruitfly/obstacles/obstacle[i]/elevation-ft                  cylinder bottom (MSL)
    /fruitfly/obstacles/obstacle[i]/radius-m, height-m            size
    /fruitfly/obstacles/obstacle[i]/visible                       bool
    /fruitfly/obstacles/obstacle[i]/threat                        0..1 orange glow while
                                                                  the fly is reacting to it

Writes into flightgear/Aircraft/FlyCabin/Models/Obstacles/:
    tower.ac            unit cylinder (radius 1 m, height 1 m) in red/white
                        obstacle-marking bands, plus a dark "Ring" around its base
    obstacle-{i}.xml    tower.ac with select/scale/glow animations bound to index i

Run:  python flightgear/tools/make_obstacles.py   (outputs are committed)
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_cabin import Mesh, write_ac  # noqa: E402  (same AC writer + FG->AC axes)

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Aircraft", "FlyCabin", "Models", "Obstacles")
MAX_OBSTACLES = 32   # keep in sync with flight_simulator/fg_scene.py
SIDES = 40
BANDS = 7            # odd, so the tower starts and ends red, like real markings
PROP = "/fruitfly/obstacles/obstacle[{i}]/{name}"


def ring(z, r=1.0):
    return [(r * math.cos(2 * math.pi * k / SIDES), r * math.sin(2 * math.pi * k / SIDES), z)
            for k in range(SIDES)]


def build_tower():
    red, white = Mesh("Red", "red"), Mesh("White", "white")
    for b in range(BANDS):
        lo, hi = ring(b / BANDS), ring((b + 1) / BANDS)
        m = red if b % 2 == 0 else white
        for k in range(SIDES):
            m.quad(lo[k], lo[(k + 1) % SIDES], hi[(k + 1) % SIDES], hi[k])
    red.poly(ring(1.0))                     # top cap
    # Flat ring around the base so the footprint is visible from above even
    # where the cylinder starts below sea level / ground.
    base = Mesh("Ring", "ring")
    inner, outer = ring(0.002, 1.0), ring(0.002, 1.15)
    for k in range(SIDES):
        base.quad(inner[k], outer[k], outer[(k + 1) % SIDES], inner[(k + 1) % SIDES])
    materials = [("red", (0.85, 0.10, 0.06), 0), ("white", (0.95, 0.95, 0.95), 0),
                 ("ring", (0.15, 0.15, 0.15), 0)]
    write_ac(os.path.join(OUT, "tower.ac"), materials, [red, white, base])


def model_xml(i):
    p = lambda name: PROP.format(i=i, name=name)
    objs = "".join(f"<object-name>{o}</object-name>" for o in ("Red", "White", "Ring"))
    return f"""<?xml version="1.0"?>
<!-- Generated by flightgear/tools/make_obstacles.py; do not edit. Obstacle index {i}. -->
<PropertyList>
  <path>tower.ac</path>

  <animation>
    <type>select</type>
    {objs}
    <condition><property>{p("visible")}</property></condition>
  </animation>

  <!-- radius: x and y; height: z. Unit cylinder, so scale = metres. -->
  <animation>
    <type>scale</type>
    {objs}
    <property>{p("radius-m")}</property>
    <x-factor>1</x-factor><x-offset>0</x-offset>
    <y-factor>1</y-factor><y-offset>0</y-offset>
    <z-factor>0</z-factor><z-offset>1</z-offset>
  </animation>
  <animation>
    <type>scale</type>
    <object-name>Red</object-name><object-name>White</object-name>
    <property>{p("height-m")}</property>
    <x-factor>0</x-factor><x-offset>1</x-offset>
    <y-factor>0</y-factor><y-offset>1</y-offset>
    <z-factor>1</z-factor><z-offset>0</z-offset>
  </animation>

  <!-- Glow orange while the fly's looming input comes from this obstacle. -->
  <animation>
    <type>material</type>
    <object-name>Red</object-name><object-name>White</object-name>
    <emission>
      <factor-prop>{p("threat")}</factor-prop>
      <red>1.0</red><green>0.45</green><blue>0.0</blue>
    </emission>
  </animation>
</PropertyList>
"""


def main():
    os.makedirs(OUT, exist_ok=True)
    build_tower()
    for i in range(MAX_OBSTACLES):
        with open(os.path.join(OUT, f"obstacle-{i}.xml"), "w", newline="\n") as f:
            f.write(model_xml(i))
    print(f"Wrote tower.ac and obstacle-0..{MAX_OBSTACLES - 1}.xml -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
